/**
 * Ed448 (RFC 8032 section 5.2, "Ed448" with a context string: dom4(0, ctx)), in pure PHP on native 64-bit ints.
 * No GMP, BCMath or phpseclib.
 *
 * Field: p = 2^448 - 2^224 - 1, elements are 16 limbs of 28 bits. Because 448 = 16 * 28 and 224 = 8 * 28, the
 * reduction 2^448 = 2^224 + 1 is a pure limb fold. A product limb sums at most 38 terms below 2^56.1, so it stays
 * under 2^62 and never overflows into a PHP float. Every add/sub carries its result, so every multiply input
