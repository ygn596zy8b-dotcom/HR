    /* ------------------------------------------------------------------ public API */

    /** Public key for a 57-byte secret key. */
    public static function public_key( string $sk ): string {
        if ( strlen( $sk ) !== self::KEY_BYTES ) {
            throw new \InvalidArgumentException( 'Ed448 secret key must be 57 bytes.' );
        }
        [ $a, $prefix ] = self::expand_secret( $sk );
        $pk = self::encode( self::mul_base_secret( $a ) );
        self::wipe( $prefix );
        return $pk;
    }

    /** Deterministic RFC 8032 signature: R || S, 114 bytes. */
    public static function sign( string $sk, string $msg, string $ctx ): string {
        if ( strlen( $sk ) !== self::KEY_BYTES ) {
            throw new \InvalidArgumentException( 'Ed448 secret key must be 57 bytes.' );
        }
        if ( strlen( $ctx ) > 255 ) {
            throw new \InvalidArgumentException( 'Ed448 context must be at most 255 bytes.' );
        }
        $dom            = 'SigEd448' . "\x00" . chr( strlen( $ctx ) ) . $ctx;
        [ $a, $prefix ] = self::expand_secret( $sk );
        $pk             = self::encode( self::mul_base_secret( $a ) );
        $nonce_in       = $dom . $prefix . $msg;
        $r              = self::sc_reduce( self::limbs_from_bytes( Keccak::shake256( $nonce_in, 114 ) ) );
        $big_r          = self::encode( self::mul_base_secret( $r ) );
        $k              = self::sc_reduce( self::limbs_from_bytes( Keccak::shake256( $dom . $big_r . $pk . $msg, 114 ) ) );
        $s              = self::sc_muladd( $k, $a, $r );
        self::wipe( $prefix );
        self::wipe( $nonce_in );
        $a = $r = array();
        return $big_r . self::limbs_to_bytes( $s, 57 );
    }

    /** Strict verification. Returns false (never throws) for any malformed input. */
    public static function verify( string $pk, string $msg, string $sig, string $ctx ): bool {
        if ( strlen( $pk ) !== self::KEY_BYTES || strlen( $sig ) !== self::SIG_BYTES || strlen( $ctx ) > 255 ) {
            return false;
        }
        $rb = substr( $sig, 0, 57 );
        $sb = substr( $sig, 57 );
        if ( strcmp( strrev( $sb ), strrev( hex2bin( self::L_HEX ) ) ) >= 0 ) {
            return false; // S >= L
        }
        $a = self::decode( $pk );
        $r = self::decode( $rb );
        if ( null === $a || null === $r ) {
            return false;
        }
        if ( self::is_identity( self::dbl( self::dbl( $a, false ), false ) ) ) {
            return false; // small-order public key
        }
        $s = self::limbs_from_bytes( $sb );
        $k = self::sc_reduce( self::limbs_from_bytes( Keccak::shake256( 'SigEd448' . "\x00" . chr( strlen( $ctx ) ) . $ctx . $rb . $pk . $msg, 114 ) ) );
        // [S]B - [k]A, then R minus that, times the cofactor 4, must be the identity.
        $neg_a = array( self::fe_sub( self::ZERO_FE, $a[0] ), $a[1], $a[2], self::fe_sub( self::ZERO_FE, $a[3] ) );
        $sbka  = self::double_mul( $s, $k, $neg_a );
        $neg   = array( self::fe_sub( self::ZERO_FE, $sbka[0] ), $sbka[1], $sbka[2], self::fe_sub( self::ZERO_FE, $sbka[3] ) );
        $chk   = self::add( $r, $neg, false );
        return self::is_identity( self::dbl( self::dbl( $chk, false ), false ) );
    }

    /* ------------------------------------------------------------------ secret expansion */

    /** @return array{0: int[], 1: string} [ scalar a mod L, prefix ] */
    private static function expand_secret( string $sk ): array {
        $h      = Keccak::shake256( $sk, 114 );
        $head   = substr( $h, 0, 57 );
        $prefix = substr( $h, 57 );
        $head[0]  = chr( ord( $head[0] ) & 0xFC );
        $head[55] = chr( ord( $head[55] ) | 0x80 );
        $head[56] = "\x00";
        $a = self::sc_reduce( self::limbs_from_bytes( $head ) );
        self::wipe( $h );
        self::wipe( $head );
        return array( $a, $prefix );
    }

    private static function wipe( string &$s ): void {
        if ( function_exists( 'sodium_memzero' ) ) {
            sodium_memzero( $s );
        }
        $s = '';
    }

