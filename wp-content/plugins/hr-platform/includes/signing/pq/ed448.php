    /** $a squared $n times. */
    private static function fe_sqrn( array $a, int $n ): array {
        for ( $i = 0; $i < $n; $i++ ) {
            $a = self::fe_sqr( $a );
        }
        return $a;
    }

    private static function fe_add( array $a, array $b ): array {
        $r = array();
        $c = 0;
        for ( $i = 0; $i < 16; $i++ ) {
            $v       = $a[ $i ] + $b[ $i ] + $c;
            $r[ $i ] = $v & self::M;
            $c       = $v >> 28;
        }
        $r[0] += $c;
        $r[8] += $c;
        return $r;
    }

    /** a - b + 2p, carried. Inputs must have limbs below 2^28 + 2^8 (true for every carried value). */
    private static function fe_sub( array $a, array $b ): array {
        $r = array();
        $c = 0;
        for ( $i = 0; $i < 16; $i++ ) {
            $v       = $a[ $i ] - $b[ $i ] + ( 8 === $i ? 0x1FFFFFFC : 0x1FFFFFFE ) + $c;
            $r[ $i ] = $v & self::M;
            $c       = $v >> 28;
        }
        $r[0] += $c;
        $r[8] += $c;
        return $r;
    }

    /** Fully reduced limbs in [0, p). */
    private static function fe_canon( array $a ): array {
        for ( $pass = 0; $pass < 2; $pass++ ) {
            $c = 0;
            for ( $i = 0; $i < 16; $i++ ) {
                $v       = $a[ $i ] + $c;
                $a[ $i ] = $v & self::M;
                $c       = $v >> 28;
            }
            $a[0] += $c;
            $a[8] += $c;
        }
        $c = 0;
        for ( $i = 0; $i < 16; $i++ ) {
            $v       = $a[ $i ] + $c;
            $a[ $i ] = $v & self::M;
            $c       = $v >> 28;
        }
        // Now 0 <= a < 2^448 < 2p: subtract p once if a >= p (selected with a mask, not a branch).
        $t      = array();
        $borrow = 0;
        for ( $i = 0; $i < 16; $i++ ) {
            $v       = $a[ $i ] - self::P[ $i ] - $borrow;
            $t[ $i ] = $v & self::M;
            $borrow  = ( $v >> 28 ) & 1;
        }
        $keep = -$borrow; // all ones when a < p (keep a), zero when a >= p (take a - p)
        for ( $i = 0; $i < 16; $i++ ) {
            $a[ $i ] = ( $a[ $i ] & $keep ) | ( $t[ $i ] & ~$keep );
        }
        return $a;
    }

    /** 56 little-endian bytes to limbs (no reduction). */
    private static function fe_from_bytes( string $b ): array {
        $r = array();
        for ( $i = 0; $i < 56; $i += 7 ) {
            $v   = unpack( 'P', substr( $b, $i, 7 ) . "\0" )[1];
            $r[] = $v & self::M;
            $r[] = $v >> 28;
        }
        return $r;
    }

    /** Canonical 56-byte encoding. */
    private static function fe_to_bytes( array $a ): string {
        $a   = self::fe_canon( $a );
        $out = '';
        for ( $i = 0; $i < 16; $i += 2 ) {
            $out .= substr( pack( 'P', $a[ $i ] | ( $a[ $i + 1 ] << 28 ) ), 0, 7 );
        }
        return $out;
    }

    private static function fe_is_zero( array $a ): bool {
        $a = self::fe_canon( $a );
        $x = 0;
        foreach ( $a as $v ) {
            $x |= $v;
        }
        return 0 === $x;
    }

    /** x^((p-3)/4), the addition chain used by @noble/curves. */
    private static function fe_pow_pm3d4( array $x ): array {
        $b2   = self::fe_mul( self::fe_sqr( $x ), $x );
        $b3   = self::fe_mul( self::fe_sqr( $b2 ), $x );
        $b6   = self::fe_mul( self::fe_sqrn( $b3, 3 ), $b3 );
        $b9   = self::fe_mul( self::fe_sqrn( $b6, 3 ), $b3 );
        $b11  = self::fe_mul( self::fe_sqrn( $b9, 2 ), $b2 );
        $b22  = self::fe_mul( self::fe_sqrn( $b11, 11 ), $b11 );
        $b44  = self::fe_mul( self::fe_sqrn( $b22, 22 ), $b22 );
        $b88  = self::fe_mul( self::fe_sqrn( $b44, 44 ), $b44 );
        $b176 = self::fe_mul( self::fe_sqrn( $b88, 88 ), $b88 );
        $b220 = self::fe_mul( self::fe_sqrn( $b176, 44 ), $b44 );
        $b222 = self::fe_mul( self::fe_sqrn( $b220, 2 ), $b2 );
        $b223 = self::fe_mul( self::fe_sqr( $b222 ), $x );
        return self::fe_mul( self::fe_sqrn( $b223, 223 ), $b222 );
    }

    /** 1/x = x^(p-2) = (x^((p-3)/4))^4 * x. */
    private static function fe_inv( array $x ): array {
        return self::fe_mul( self::fe_sqrn( self::fe_pow_pm3d4( $x ), 2 ), $x );
    }

    /* ------------------------------------------------------------------ points */

    /**
     * Doubling (dbl-2008-hwcd, a = 1): A = X^2, B = Y^2, C = 2Z^2, G = A + B, E = (X + Y)^2 - G, F = G - C,
     * H = A - B; X3 = EF, Y3 = GH, Z3 = FG, T3 = EH. T is computed only when the next step is an addition.
     */
    private static function dbl( array $p, bool $want_t ): array {
        [ $x, $y, $z ] = $p;
        $a  = self::fe_sqr( $x );
        $b  = self::fe_sqr( $y );
        $zz = self::fe_sqr( $z );
        $g  = self::fe_add( $a, $b );
        $e  = self::fe_sub( self::fe_sqr( self::fe_add( $x, $y ) ), $g );
        $f  = self::fe_sub( $g, self::fe_add( $zz, $zz ) );
        $h  = self::fe_sub( $a, $b );
        return array(
            self::fe_mul( $e, $f ),
            self::fe_mul( $g, $h ),
            self::fe_mul( $f, $g ),
            $want_t ? self::fe_mul( $e, $h ) : null,
        );
    }

    /**
     * Addition (add-2008-hwcd, a = 1). $q may carry d*T in slot 4 (precomputed tables), else T*d is computed.
     */
    private static function add( array $p, array $q, bool $want_t ): array {
        $a  = self::fe_mul( $p[0], $q[0] );
        $b  = self::fe_mul( $p[1], $q[1] );
        $c  = isset( $q[4] ) ? self::fe_mul( $p[3], $q[4] ) : self::fe_mul( self::fe_mul( $p[3], $q[3] ), self::D );
        $d  = self::fe_mul( $p[2], $q[2] );
        $e  = self::fe_sub( self::fe_sub( self::fe_mul( self::fe_add( $p[0], $p[1] ), self::fe_add( $q[0], $q[1] ) ), $a ), $b );
        $f  = self::fe_sub( $d, $c );
        $g  = self::fe_add( $d, $c );
        $h  = self::fe_sub( $b, $a );
        return array(
            self::fe_mul( $e, $f ),
            self::fe_mul( $g, $h ),
            self::fe_mul( $f, $g ),
            $want_t ? self::fe_mul( $e, $h ) : null,
        );
    }

    private static function is_identity( array $p ): bool {
        return self::fe_is_zero( $p[0] ) && self::fe_is_zero( self::fe_sub( $p[1], $p[2] ) );
    }

    private static function encode( array $p ): string {
        $zi = self::fe_inv( $p[2] );
        $x  = self::fe_canon( self::fe_mul( $p[0], $zi ) );
        $y  = self::fe_to_bytes( self::fe_mul( $p[1], $zi ) );
        return $y . chr( ( $x[0] & 1 ) << 7 );
    }

    /** Strict decoding (RFC 8032 5.2.3). Returns null for anything that is not a canonical point encoding. */
    private static function decode( string $b ): ?array {
        $last = ord( $b[56] );
        if ( 0 !== ( $last & 0x7F ) ) {
            return null;
        }
        $yb = substr( $b, 0, 56 );
        $y  = self::fe_from_bytes( $yb );
        if ( self::fe_to_bytes( $y ) !== $yb ) {
            return null; // y >= p
        }
        $yy  = self::fe_sqr( $y );
        $u   = self::fe_sub( $yy, self::ONE_FE );
        $v   = self::fe_sub( self::fe_mul( $yy, self::D ), self::ONE_FE );
        $u2v = self::fe_mul( self::fe_sqr( $u ), $v );
        $u3v = self::fe_mul( $u2v, $u );
        $x   = self::fe_mul( $u3v, self::fe_pow_pm3d4( self::fe_mul( self::fe_mul( $u3v, $u2v ), $v ) ) );
        if ( ! self::fe_is_zero( self::fe_sub( self::fe_mul( self::fe_sqr( $x ), $v ), $u ) ) ) {
            return null; // not on the curve
        }
        $x    = self::fe_canon( $x );
        $sign = $last >> 7;
        $zero = 0;
        foreach ( $x as $l ) {
            $zero |= $l;
        }
        if ( 0 === $zero && 1 === $sign ) {
            return null;
        }
        if ( ( $x[0] & 1 ) !== $sign ) {
            $x = self::fe_sub( self::ZERO_FE, $x );
        }
        return array( $x, $y, self::ONE_FE, self::fe_mul( $x, $y ) );
    }

    /** [j]P for j = 0..15, each with d*T in slot 4. */
    private static function table( array $p ): array {
        $t    = array( array( self::ZERO_FE, self::ONE_FE, self::ONE_FE, self::ZERO_FE ) );
        $t[1] = $p;
        for ( $j = 2; $j < 16; $j++ ) {
            $t[ $j ] = ( 0 === ( $j & 1 ) ) ? self::dbl( $t[ $j >> 1 ], true ) : self::add( $t[ $j - 1 ], $p, true );
        }
        foreach ( $t as $j => $pt ) {
            $t[ $j ][4] = self::fe_mul( $pt[3], self::D );
        }
        return $t;
    }

    private static function base_table(): array {
        if ( null === self::$base_table ) {
            self::$base_table = self::table( array( self::GX, self::GY, self::ONE_FE, self::fe_mul( self::GX, self::GY ) ) );
        }
        return self::$base_table;
    }

    /** 4-bit digits of a reduced scalar, most significant first (112 digits). */
    private static function nibbles( array $k ): array {
        $out = array();
        for ( $i = 15; $i >= 0; $i-- ) {
            $l = $k[ $i ] ?? 0;
            for ( $s = 24; $s >= 0; $s -= 4 ) {
                $out[] = ( $l >> $s ) & 15;
            }
        }
        return $out;
    }

    /**
     * [k]B for a secret scalar: fixed 4-bit windows, an addition at every window (also for digit 0, which adds the
     * identity) and a masked table lookup, so the sequence of operations and memory reads does not follow the key.
     */
    private static function mul_base_secret( array $k ): array {
        $tab = self::base_table();
        $acc = array( self::ZERO_FE, self::ONE_FE, self::ONE_FE, self::ZERO_FE );
        foreach ( self::nibbles( $k ) as $n => $digit ) {
            if ( $n > 0 ) {
                $acc = self::dbl( $acc, false );
                $acc = self::dbl( $acc, false );
                $acc = self::dbl( $acc, false );
                $acc = self::dbl( $acc, true );
            }
            $acc = self::add( $acc, self::select( $tab, $digit ), false );
        }
        return $acc;
    }

    /** Constant-time-style table read: every entry is touched, the wanted one is kept with a mask. */
    private static function select( array $tab, int $digit ): array {
        $out = array( self::ZERO_FE, self::ZERO_FE, self::ZERO_FE, self::ZERO_FE, self::ZERO_FE );
        foreach ( $tab as $j => $pt ) {
            $m = ( ( $j ^ $digit ) - 1 ) >> 63; // -1 when j == digit, else 0
            for ( $c = 0; $c < 5; $c++ ) {
                if ( 3 === $c ) {
                    continue; // T itself is not needed: additions use d*T in slot 4
                }
                $src = $pt[ $c ];
                $dst = $out[ $c ];
                for ( $i = 0; $i < 16; $i++ ) {
                    $dst[ $i ] |= $src[ $i ] & $m;
                }
                $out[ $c ] = $dst;
            }
        }
        $out[3] = null;
        return $out;
    }

    /** [s]B + [k]P for public scalars (verification), sharing the doublings (Straus). */
    private static function double_mul( array $s, array $k, array $p ): array {
        $tb  = self::base_table();
        $tp  = self::table( $p );
        $ds  = self::nibbles( $s );
        $dk  = self::nibbles( $k );
        $acc = array( self::ZERO_FE, self::ONE_FE, self::ONE_FE, self::ZERO_FE );
        for ( $n = 0; $n < 112; $n++ ) {
            if ( $n > 0 ) {
                $acc = self::dbl( $acc, false );
                $acc = self::dbl( $acc, false );
                $acc = self::dbl( $acc, false );
                $acc = self::dbl( $acc, true );
            }
            $last = 111 === $n; // the caller adds the result to R, which needs T
            if ( 0 !== $ds[ $n ] ) {
                $acc = self::add( $acc, $tb[ $ds[ $n ] ], $last || 0 !== $dk[ $n ] );
            }
            if ( 0 !== $dk[ $n ] ) {
                $acc = self::add( $acc, $tp[ $dk[ $n ] ], $last );
            }
        }
        return $acc;
    }

    /* ------------------------------------------------------------------ scalars mod L */

    /** Little-endian bytes to normalized 28-bit limbs. */
    private static function limbs_from_bytes( string $b ): array {
        $pad = ( 7 - strlen( $b ) % 7 ) % 7;
        $b  .= str_repeat( "\0", $pad );
        $r   = array();
        for ( $i = 0, $n = strlen( $b ); $i < $n; $i += 7 ) {
            $v   = unpack( 'P', substr( $b, $i, 7 ) . "\0" )[1];
            $r[] = $v & self::M;
            $r[] = $v >> 28;
        }
        return $r;
    }

    /** Normalized limbs (value < 2^(28 * 16)) to $len little-endian bytes. */
    private static function limbs_to_bytes( array $a, int $len ): string {
        $a   = array_pad( $a, 16, 0 );
        $out = '';
        for ( $i = 0; $i < 16; $i += 2 ) {
            $out .= substr( pack( 'P', $a[ $i ] | ( $a[ $i + 1 ] << 28 ) ), 0, 7 );
        }
        return str_pad( $out, $len, "\0" );
    }

    /** Propagate carries so every limb is in [0, 2^28); returns a fixed-length array. */
    private static function carry( array $a, int $len ): array {
        $r = array();
        $c = 0;
        for ( $i = 0; $i < $len; $i++ ) {
            $v       = ( $a[ $i ] ?? 0 ) + $c;
            $r[ $i ] = $v & self::M;
            $c       = $v >> 28;
        }
        return $r;
    }

    /**
     * x mod L for x < 2^912 given as normalized limbs. Four folds of hi * c + lo (hi = x >> 446) bring x below
     * 2^446 + 2^225 < 2L; one masked subtraction finishes. The fold count is fixed, not data dependent.
     */
    private static function sc_reduce( array $x ): array {
        $x = self::carry( $x, 34 );
        for ( $round = 0; $round < 4; $round++ ) {
            $hi = array();
            for ( $j = 0; $j < 18; $j++ ) {
                $hi[ $j ] = ( ( $x[ 15 + $j ] ?? 0 ) >> 26 ) | ( ( ( $x[ 16 + $j ] ?? 0 ) << 2 ) & self::M );
            }
            $lo     = array_slice( $x, 0, 16 );
            $lo[15] &= 0x3FFFFFF;
            for ( $i = 0; $i < 18; $i++ ) {
                $h = $hi[ $i ];
                for ( $j = 0; $j < 8; $j++ ) {
                    $lo[ $i + $j ] = ( $lo[ $i + $j ] ?? 0 ) + $h * self::C[ $j ];
                }
            }
            $x = self::carry( $lo, 34 );
        }
        // Here x < 2L: subtract L if x >= L.
        $t      = array();
        $borrow = 0;
        for ( $i = 0; $i < 16; $i++ ) {
            $v       = $x[ $i ] - self::L[ $i ] - $borrow;
            $t[ $i ] = $v & self::M;
            $borrow  = ( $v >> 28 ) & 1;
        }
        $v      = $x[16] - $borrow; // x < 2^447, so only limb 16 can still be non-zero above L's 16 limbs
        $keep   = -( ( $v >> 63 ) & 1 ); // all ones when x < L
        $r      = array();
        for ( $i = 0; $i < 16; $i++ ) {
            $r[ $i ] = ( $x[ $i ] & $keep ) | ( $t[ $i ] & ~$keep );
        }
        return $r;
    }

    /** (a * b + c) mod L for reduced a, b, c. */
    private static function sc_muladd( array $a, array $b, array $c ): array {
        $p = array_fill( 0, 34, 0 );
        for ( $i = 0; $i < 16; $i++ ) {
            $p[ $i ] += $c[ $i ];
            $ai = $a[ $i ];
            for ( $j = 0; $j < 16; $j++ ) {
                $p[ $i + $j ] += $ai * $b[ $j ];
            }
        }
        return self::sc_reduce( self::carry( $p, 34 ) );
    }
