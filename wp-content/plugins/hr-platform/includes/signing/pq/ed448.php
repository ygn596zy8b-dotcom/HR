 * Points: extended twisted-Edwards coordinates (X:Y:Z:T), x = X/Z, y = Y/Z, xy = T/Z, with the complete
 * Hisil-Wong-Carter-Dawson (2008) formulas for a = 1 (complete because d = -39081 is not a square).
