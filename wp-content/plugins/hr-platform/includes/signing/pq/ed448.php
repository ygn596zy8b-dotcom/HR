 *
 * Verification follows @noble/curves 2.4.0 strict mode exactly: a 57-byte key and 114-byte signature, canonical
 * point encodings only (y < p, unused bits zero, no "x = 0 with sign bit set"), S < L, small-order public keys
 * rejected, cofactored equation [4](R + kA - SB) = 0.
 *
 * The field multiply and square bodies are generated by tests/pq/codegen.php; do not edit them by hand.
 */

